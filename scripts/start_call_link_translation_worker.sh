#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MODEL_ROUTING_FILE="${MODEL_ROUTING_FILE:-}"
MODEL_ROUTING_PROFILE="${MODEL_ROUTING_PROFILE:-}"

if [[ "${1:-}" == "-h" || "${1:-}" == "--help" ]]; then
  cat <<'USAGE'
Usage:
  TRANSLATION_WORKER_CALL_ID=<callId> scripts/start_call_link_translation_worker.sh
  MODEL_ROUTING_PROFILE=domestic_server_qwen3_hymt2_voxcpm2 TRANSLATION_WORKER_CALL_ID=<callId> scripts/start_call_link_translation_worker.sh

Starts the Call Link Translation Worker. When MODEL_ROUTING_FILE or
MODEL_ROUTING_PROFILE is set, the script loads the translationWorker env group
from release/domestic/model-routing.json. Explicit environment variables keep
priority over profile values.

Required:
  TRANSLATION_WORKER_CALL_ID
  INTERNAL_API_SECRET

Common optional:
  API_BASE_URL
  MODEL_ROUTING_FILE
  MODEL_ROUTING_PROFILE
  TRANSLATION_WORKER_PARTICIPANT_NAME
  TTS_AUDIO_SINK_ENDPOINT
  TTS_AUDIO_SINK_API_KEY
USAGE
  exit 0
fi

capture_explicit_env() {
  local name="$1"
  if [[ "${!name+x}" == "x" ]]; then
    printf -v "USER_${name}_SET" "%s" "1"
    printf -v "USER_${name}" "%s" "${!name}"
  else
    printf -v "USER_${name}_SET" "%s" "0"
  fi
}

restore_explicit_env() {
  local name="$1"
  local set_name="USER_${name}_SET"
  local value_name="USER_${name}"
  if [[ "${!set_name}" == "1" ]]; then
    printf -v "$name" "%s" "${!value_name}"
  fi
}

for name in \
  ASR_HTTP_ENDPOINT \
  ASR_HTTP_FLUSH_ENDPOINT \
  ASR_STREAM_ENDPOINT \
  ASR_HTTP_API_KEY \
  TRANSLATION_BASE_URL \
  TRANSLATION_MODEL \
  TRANSLATION_API_KEY \
  TRANSLATION_STREAMING_ENABLED \
  TTS_PROVIDER \
  TTS_MODEL \
  TTS_HTTP_ENDPOINT \
  TTS_STREAM_ENDPOINT \
  TTS_WARMUP_ENDPOINT \
  TTS_HTTP_API_KEY \
  TTS_AUDIO_SINK_ENDPOINT \
  TTS_AUDIO_SINK_API_KEY; do
  capture_explicit_env "$name"
done

if [[ -n "$MODEL_ROUTING_FILE" || -n "$MODEL_ROUTING_PROFILE" ]]; then
  eval "$(MODEL_ROUTING_FILE="$MODEL_ROUTING_FILE" \
    MODEL_ROUTING_PROFILE="$MODEL_ROUTING_PROFILE" \
      node "$ROOT_DIR/scripts/render_model_routing_env.mjs" --group translationWorker)"
fi

for name in \
  ASR_HTTP_ENDPOINT \
  ASR_HTTP_FLUSH_ENDPOINT \
  ASR_STREAM_ENDPOINT \
  ASR_HTTP_API_KEY \
  TRANSLATION_BASE_URL \
  TRANSLATION_MODEL \
  TRANSLATION_API_KEY \
  TRANSLATION_STREAMING_ENABLED \
  TTS_PROVIDER \
  TTS_MODEL \
  TTS_HTTP_ENDPOINT \
  TTS_STREAM_ENDPOINT \
  TTS_WARMUP_ENDPOINT \
  TTS_HTTP_API_KEY \
  TTS_AUDIO_SINK_ENDPOINT \
  TTS_AUDIO_SINK_API_KEY; do
  restore_explicit_env "$name"
done

TRANSLATION_WORKER_CALL_ID="${TRANSLATION_WORKER_CALL_ID:-}"
API_BASE_URL="${API_BASE_URL:-http://127.0.0.1:3100}"
INTERNAL_API_SECRET="${INTERNAL_API_SECRET:-}"
TRANSLATION_WORKER_PARTICIPANT_NAME="${TRANSLATION_WORKER_PARTICIPANT_NAME:-translation-worker}"
TRANSLATION_WORKER_API_TIMEOUT_MS="${TRANSLATION_WORKER_API_TIMEOUT_MS:-5000}"
TRANSLATION_WORKER_AUDIO_SAMPLE_RATE="${TRANSLATION_WORKER_AUDIO_SAMPLE_RATE:-24000}"
TRANSLATION_WORKER_AUDIO_FRAME_SIZE_MS="${TRANSLATION_WORKER_AUDIO_FRAME_SIZE_MS:-100}"
CALL_FULL_DUPLEX_ENABLED="${CALL_FULL_DUPLEX_ENABLED:-false}"
CALL_BARGE_IN_MIN_SPEECH_MS="${CALL_BARGE_IN_MIN_SPEECH_MS:-240}"
CALL_BARGE_IN_MIN_PROBABILITY="${CALL_BARGE_IN_MIN_PROBABILITY:-0.5}"
CALL_BARGE_IN_COOLDOWN_MS="${CALL_BARGE_IN_COOLDOWN_MS:-800}"
CALL_BARGE_IN_PRE_ROLL_MS="${CALL_BARGE_IN_PRE_ROLL_MS:-400}"
CALL_ECHO_START_GATE_ENABLED="${CALL_ECHO_START_GATE_ENABLED:-true}"
CALL_ECHO_BARGE_IN_MIN_SPEECH_MS="${CALL_ECHO_BARGE_IN_MIN_SPEECH_MS:-480}"
CALL_ECHO_BARGE_IN_MIN_PROBABILITY="${CALL_ECHO_BARGE_IN_MIN_PROBABILITY:-0.72}"
CALL_BACKCHANNEL_MAX_SPEECH_MS="${CALL_BACKCHANNEL_MAX_SPEECH_MS:-360}"
PROVIDER_FALLBACK_FAILURE_THRESHOLD="${PROVIDER_FALLBACK_FAILURE_THRESHOLD:-1}"
PROVIDER_FALLBACK_COOLDOWN_MS="${PROVIDER_FALLBACK_COOLDOWN_MS:-30000}"
CALL_PIPELINE_END_GRACE_MS="${CALL_PIPELINE_END_GRACE_MS:-1500}"
LLM_FALLBACK_COOLDOWN_MS="${LLM_FALLBACK_COOLDOWN_MS:-$PROVIDER_FALLBACK_COOLDOWN_MS}"
ASR_HTTP_TIMEOUT_MS="${ASR_HTTP_TIMEOUT_MS:-10000}"
TRANSLATION_TIMEOUT_MS="${TRANSLATION_TIMEOUT_MS:-20000}"
TRANSLATION_MAX_TOKENS="${TRANSLATION_MAX_TOKENS:-${LMSTUDIO_MAX_TOKENS:-512}}"
TTS_HTTP_TIMEOUT_MS="${TTS_HTTP_TIMEOUT_MS:-10000}"
TTS_AUDIO_SINK_TIMEOUT_MS="${TTS_AUDIO_SINK_TIMEOUT_MS:-5000}"
ASR_HTTP_ENDPOINT="${ASR_HTTP_ENDPOINT:-http://127.0.0.1:8001/asr/transcribe}"
TRANSLATION_BASE_URL="${TRANSLATION_BASE_URL:-${LMSTUDIO_BASE_URL:-http://127.0.0.1:1234/v1}}"
TRANSLATION_MODEL="${TRANSLATION_MODEL:-${LMSTUDIO_MODEL:-tencent/Hy-MT2-1.8B}}"
TRANSLATION_API_KEY="${TRANSLATION_API_KEY:-${LMSTUDIO_API_KEY:-}}"

if [[ -n "${TTS_HTTP_ENDPOINT:-}" ]]; then
  TTS_PROVIDER="${TTS_PROVIDER:-voxcpm2}"
  TTS_MODEL="${TTS_MODEL:-VoxCPM2}"
fi

if [[ -z "$TRANSLATION_WORKER_CALL_ID" ]]; then
  echo "TRANSLATION_WORKER_CALL_ID is required." >&2
  exit 2
fi

if [[ -z "$INTERNAL_API_SECRET" ]]; then
  echo "INTERNAL_API_SECRET is required for Worker room token and event APIs." >&2
  exit 2
fi

MODEL_ROUTING_FILE="$MODEL_ROUTING_FILE" \
MODEL_ROUTING_PROFILE="$MODEL_ROUTING_PROFILE" \
TRANSLATION_WORKER_CALL_ID="$TRANSLATION_WORKER_CALL_ID" \
TRANSLATION_WORKER_PARTICIPANT_NAME="$TRANSLATION_WORKER_PARTICIPANT_NAME" \
TRANSLATION_WORKER_API_TIMEOUT_MS="$TRANSLATION_WORKER_API_TIMEOUT_MS" \
TRANSLATION_WORKER_AUDIO_SAMPLE_RATE="$TRANSLATION_WORKER_AUDIO_SAMPLE_RATE" \
TRANSLATION_WORKER_AUDIO_FRAME_SIZE_MS="$TRANSLATION_WORKER_AUDIO_FRAME_SIZE_MS" \
CALL_FULL_DUPLEX_ENABLED="$CALL_FULL_DUPLEX_ENABLED" \
CALL_BARGE_IN_MIN_SPEECH_MS="$CALL_BARGE_IN_MIN_SPEECH_MS" \
CALL_BARGE_IN_MIN_PROBABILITY="$CALL_BARGE_IN_MIN_PROBABILITY" \
CALL_BARGE_IN_COOLDOWN_MS="$CALL_BARGE_IN_COOLDOWN_MS" \
CALL_BARGE_IN_PRE_ROLL_MS="$CALL_BARGE_IN_PRE_ROLL_MS" \
CALL_ECHO_START_GATE_ENABLED="$CALL_ECHO_START_GATE_ENABLED" \
CALL_ECHO_BARGE_IN_MIN_SPEECH_MS="$CALL_ECHO_BARGE_IN_MIN_SPEECH_MS" \
CALL_ECHO_BARGE_IN_MIN_PROBABILITY="$CALL_ECHO_BARGE_IN_MIN_PROBABILITY" \
CALL_BACKCHANNEL_MAX_SPEECH_MS="$CALL_BACKCHANNEL_MAX_SPEECH_MS" \
PROVIDER_FALLBACK_FAILURE_THRESHOLD="$PROVIDER_FALLBACK_FAILURE_THRESHOLD" \
PROVIDER_FALLBACK_COOLDOWN_MS="$PROVIDER_FALLBACK_COOLDOWN_MS" \
CALL_PIPELINE_END_GRACE_MS="$CALL_PIPELINE_END_GRACE_MS" \
LLM_FALLBACK_COOLDOWN_MS="$LLM_FALLBACK_COOLDOWN_MS" \
API_BASE_URL="$API_BASE_URL" \
INTERNAL_API_SECRET="$INTERNAL_API_SECRET" \
ASR_HTTP_ENDPOINT="$ASR_HTTP_ENDPOINT" \
ASR_HTTP_FLUSH_ENDPOINT="${ASR_HTTP_FLUSH_ENDPOINT:-}" \
ASR_STREAM_ENDPOINT="${ASR_STREAM_ENDPOINT:-}" \
ASR_STREAM_FALLBACK_TO_HTTP="${ASR_STREAM_FALLBACK_TO_HTTP:-true}" \
ASR_HTTP_API_KEY="${ASR_HTTP_API_KEY:-}" \
ASR_HTTP_TIMEOUT_MS="$ASR_HTTP_TIMEOUT_MS" \
ASR_FALLBACK_PROVIDER="${ASR_FALLBACK_PROVIDER:-}" \
ASR_FALLBACK_MODEL="${ASR_FALLBACK_MODEL:-}" \
ASR_FALLBACK_HTTP_ENDPOINT="${ASR_FALLBACK_HTTP_ENDPOINT:-}" \
ASR_FALLBACK_HTTP_FLUSH_ENDPOINT="${ASR_FALLBACK_HTTP_FLUSH_ENDPOINT:-}" \
ASR_FALLBACK_STREAM_ENDPOINT="${ASR_FALLBACK_STREAM_ENDPOINT:-}" \
ASR_FALLBACK_HTTP_API_KEY="${ASR_FALLBACK_HTTP_API_KEY:-}" \
ASR_FALLBACK_HTTP_TIMEOUT_MS="${ASR_FALLBACK_HTTP_TIMEOUT_MS:-10000}" \
TRANSLATION_BASE_URL="$TRANSLATION_BASE_URL" \
TRANSLATION_MODEL="$TRANSLATION_MODEL" \
TRANSLATION_API_KEY="$TRANSLATION_API_KEY" \
TRANSLATION_TIMEOUT_MS="$TRANSLATION_TIMEOUT_MS" \
TRANSLATION_MAX_TOKENS="$TRANSLATION_MAX_TOKENS" \
TRANSLATION_STREAMING_ENABLED="${TRANSLATION_STREAMING_ENABLED:-false}" \
TRANSLATION_FALLBACK_PROVIDER="${TRANSLATION_FALLBACK_PROVIDER:-}" \
TRANSLATION_FALLBACK_BASE_URL="${TRANSLATION_FALLBACK_BASE_URL:-}" \
TRANSLATION_FALLBACK_MODEL="${TRANSLATION_FALLBACK_MODEL:-}" \
TRANSLATION_FALLBACK_API_KEY="${TRANSLATION_FALLBACK_API_KEY:-}" \
TRANSLATION_FALLBACK_TIMEOUT_MS="${TRANSLATION_FALLBACK_TIMEOUT_MS:-20000}" \
TRANSLATION_FALLBACK_MAX_TOKENS="${TRANSLATION_FALLBACK_MAX_TOKENS:-512}" \
TRANSLATION_FALLBACK_STREAMING_ENABLED="${TRANSLATION_FALLBACK_STREAMING_ENABLED:-false}" \
TTS_PROVIDER="${TTS_PROVIDER:-}" \
TTS_MODEL="${TTS_MODEL:-}" \
TTS_HTTP_ENDPOINT="${TTS_HTTP_ENDPOINT:-}" \
TTS_STREAM_ENDPOINT="${TTS_STREAM_ENDPOINT:-}" \
TTS_WARMUP_ENDPOINT="${TTS_WARMUP_ENDPOINT:-}" \
TTS_WARMUP_MAX_MS="${TTS_WARMUP_MAX_MS:-15000}" \
TTS_HTTP_API_KEY="${TTS_HTTP_API_KEY:-}" \
TTS_HTTP_TIMEOUT_MS="$TTS_HTTP_TIMEOUT_MS" \
TTS_FALLBACK_PROVIDER="${TTS_FALLBACK_PROVIDER:-}" \
TTS_FALLBACK_MODEL="${TTS_FALLBACK_MODEL:-}" \
TTS_FALLBACK_HTTP_ENDPOINT="${TTS_FALLBACK_HTTP_ENDPOINT:-}" \
TTS_FALLBACK_STREAM_ENDPOINT="${TTS_FALLBACK_STREAM_ENDPOINT:-}" \
TTS_FALLBACK_WARMUP_ENDPOINT="${TTS_FALLBACK_WARMUP_ENDPOINT:-}" \
TTS_FALLBACK_HTTP_API_KEY="${TTS_FALLBACK_HTTP_API_KEY:-}" \
TTS_FALLBACK_HTTP_TIMEOUT_MS="${TTS_FALLBACK_HTTP_TIMEOUT_MS:-10000}" \
TTS_AUDIO_SINK_ENDPOINT="${TTS_AUDIO_SINK_ENDPOINT:-}" \
TTS_AUDIO_SINK_API_KEY="${TTS_AUDIO_SINK_API_KEY:-}" \
TTS_AUDIO_SINK_TIMEOUT_MS="$TTS_AUDIO_SINK_TIMEOUT_MS" \
  npm run dev -w @translation/translation-worker
